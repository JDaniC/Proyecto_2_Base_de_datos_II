-- Instantanea de receta: mismos datos de medicamentos exigidos por los modelos documentales.
CREATE OR REPLACE FUNCTION instantanea_receta_valida(datos jsonb) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE medicamento jsonb; campo text;
BEGIN
 IF jsonb_typeof(datos) IS DISTINCT FROM 'object'
    OR jsonb_typeof(datos->'medicamentos') IS DISTINCT FROM 'array' THEN RETURN false; END IF;
 IF jsonb_array_length(datos->'medicamentos') NOT BETWEEN 1 AND 100 THEN RETURN false; END IF;
 FOREACH campo IN ARRAY ARRAY['prescriptor_nombre_historico','colegiado_historico'] LOOP
  IF jsonb_typeof(datos->campo) IS DISTINCT FROM 'string' OR btrim(datos->>campo)='' THEN RETURN false; END IF;
 END LOOP;
 FOR medicamento IN SELECT value FROM jsonb_array_elements(datos->'medicamentos') LOOP
  FOREACH campo IN ARRAY ARRAY['medicamento_id','nombre','presentacion','concentracion','dosis','frecuencia','duracion','via','indicaciones'] LOOP
   IF jsonb_typeof(medicamento->campo) IS DISTINCT FROM 'string' OR btrim(medicamento->>campo)='' THEN RETURN false; END IF;
  END LOOP;
 END LOOP;
 RETURN true;
END $$;
