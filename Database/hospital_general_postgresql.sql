CREATE OR REPLACE FUNCTION verificar_principal() RETURNS trigger LANGUAGE plpgsql
SET search_path = hospital_general, pg_temp AS $$
DECLARE consulta_id bigint;
BEGIN
  consulta_id := CASE WHEN TG_OP='DELETE' THEN OLD.id_consulta ELSE NEW.id_consulta END;
  PERFORM 1 FROM consulta WHERE id_consulta=consulta_id FOR UPDATE;
  IF EXISTS(SELECT 1 FROM diagnostico WHERE id_consulta=consulta_id) AND
