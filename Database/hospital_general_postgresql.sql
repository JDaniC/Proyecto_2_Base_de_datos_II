-- Base relacional del Hospital General (PostgreSQL)
-- Basada en las 46 entidades y atributos del modelo relacional del proyecto.
-- Ejecutar conectado a la base de datos PostgreSQL de destino.

BEGIN;

CREATE SCHEMA IF NOT EXISTS hospital_general;
SET search_path TO hospital_general, public;

CREATE TABLE IF NOT EXISTS paciente (
    id_paciente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cui VARCHAR(20) UNIQUE,
    primer_nombre VARCHAR(80) NOT NULL,
    segundo_nombre VARCHAR(80),
    primer_apellido VARCHAR(80) NOT NULL,
    segundo_apellido VARCHAR(80),
    fecha_nacimiento DATE,
    sexo VARCHAR(30),
    tipo_sangre VARCHAR(10),
    telefono_principal VARCHAR(30),
    correo_principal VARCHAR(254),
    direccion TEXT,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contacto_emergencia (
    id_contacto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
    primer_nombre VARCHAR(80) NOT NULL,
    segundo_nombre VARCHAR(80),
    primer_apellido VARCHAR(80) NOT NULL,
    segundo_apellido VARCHAR(80),
    parentesco VARCHAR(60) NOT NULL,
    telefono VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS historial_clinico (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL UNIQUE REFERENCES paciente(id_paciente),
    numero_historial VARCHAR(40) NOT NULL UNIQUE,
    fecha_apertura DATE NOT NULL DEFAULT CURRENT_DATE,
    observaciones_generales TEXT,
    estado_historial VARCHAR(30) NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE IF NOT EXISTS alergia (
    id_alergia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE IF NOT EXISTS paciente_alergia (
    id_paciente_alergia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
    id_alergia BIGINT NOT NULL REFERENCES alergia(id_alergia),
    tipo_reaccion TEXT,
    severidad VARCHAR(40),
    observaciones TEXT,
    fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (id_paciente, id_alergia)
);

CREATE TABLE IF NOT EXISTS antecedente_medico (
    id_antecedente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
    tipo VARCHAR(100) NOT NULL,
    descripcion TEXT NOT NULL,
    fecha_diagnostico DATE,
    observaciones TEXT
);

CREATE TABLE IF NOT EXISTS personal_medico (
    id_personal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primer_nombre VARCHAR(80) NOT NULL,
    segundo_nombre VARCHAR(80),
    primer_apellido VARCHAR(80) NOT NULL,
    segundo_apellido VARCHAR(80),
    numero_colegiado VARCHAR(50) UNIQUE,
    entidad_colegiacion VARCHAR(150),
    telefono_principal VARCHAR(30),
    correo_principal VARCHAR(254),
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE IF NOT EXISTS especialidad (
    id_especialidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE IF NOT EXISTS personal_especialidad (
    id_personal BIGINT NOT NULL REFERENCES personal_medico(id_personal),
    id_especialidad BIGINT NOT NULL REFERENCES especialidad(id_especialidad),
    PRIMARY KEY (id_personal, id_especialidad)
);

CREATE TABLE IF NOT EXISTS cita (
    id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
    id_personal_programado BIGINT NOT NULL REFERENCES personal_medico(id_personal),
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP,
    motivo_solicitud TEXT NOT NULL,
    estado_cita VARCHAR(30) NOT NULL DEFAULT 'PROGRAMADA',
    observaciones TEXT,
    CHECK (fecha_hora_fin IS NULL OR fecha_hora_fin >= fecha_hora_inicio)
);

CREATE TABLE IF NOT EXISTS consulta (
    id_consulta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_historial BIGINT NOT NULL REFERENCES historial_clinico(id_historial),
    id_personal_atendio BIGINT NOT NULL REFERENCES personal_medico(id_personal),
    id_cita BIGINT REFERENCES cita(id_cita),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo_consulta TEXT NOT NULL,
    sintomas TEXT,
    observaciones TEXT,
    notas_medicas TEXT
);

CREATE TABLE IF NOT EXISTS signos_vitales (
    id_signos_vitales BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta BIGINT NOT NULL REFERENCES consulta(id_consulta),
    fecha_hora_medicion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    peso_kg NUMERIC(7,3),
    altura_cm NUMERIC(6,2),
    temperatura_c NUMERIC(4,1),
    presion_sistolica_mmhg SMALLINT,
    presion_diastolica_mmhg SMALLINT,
    frecuencia_cardiaca_lpm SMALLINT,
    frecuencia_respiratoria_rpm SMALLINT,
    saturacion_oxigeno_pct NUMERIC(5,2),
    CHECK (peso_kg IS NULL OR peso_kg >= 0),
    CHECK (altura_cm IS NULL OR altura_cm >= 0),
    CHECK (saturacion_oxigeno_pct IS NULL OR saturacion_oxigeno_pct BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS catalogo_diagnostico (
    id_catalogo_diagnostico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sistema VARCHAR(100),
    version VARCHAR(40),
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    descripcion TEXT,
    UNIQUE (sistema, version, codigo)
);

CREATE TABLE IF NOT EXISTS diagnostico (
    id_diagnostico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta BIGINT NOT NULL REFERENCES consulta(id_consulta),
    id_catalogo_diagnostico BIGINT NOT NULL REFERENCES catalogo_diagnostico(id_catalogo_diagnostico),
    tipo VARCHAR(50),
    fecha_diagnostico DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE IF NOT EXISTS tratamiento (
    id_tratamiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta BIGINT NOT NULL REFERENCES consulta(id_consulta),
    descripcion TEXT NOT NULL,
    fecha_inicio DATE,
    fecha_fin DATE,
    indicaciones TEXT,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVO',
    CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE IF NOT EXISTS diagnostico_tratamiento (
    id_diagnostico BIGINT NOT NULL REFERENCES diagnostico(id_diagnostico),
    id_tratamiento BIGINT NOT NULL REFERENCES tratamiento(id_tratamiento),
    PRIMARY KEY (id_diagnostico, id_tratamiento)
);

CREATE TABLE IF NOT EXISTS procedimiento (
    id_procedimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE IF NOT EXISTS procedimiento_realizado (
    id_procedimiento_realizado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_procedimiento BIGINT NOT NULL REFERENCES procedimiento(id_procedimiento),
    id_consulta BIGINT NOT NULL REFERENCES consulta(id_consulta),
    id_personal_responsable BIGINT NOT NULL REFERENCES personal_medico(id_personal),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resultado TEXT,
    observaciones TEXT
);

CREATE TABLE IF NOT EXISTS laboratorio_farmaceutico (
    id_laboratorio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS unidad_medida (
    id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    dimension VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS medicamento (
    id_medicamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL,
    presentacion VARCHAR(150),
    id_laboratorio BIGINT REFERENCES laboratorio_farmaceutico(id_laboratorio),
    cantidad_base NUMERIC(12,4),
    id_unidad_base BIGINT REFERENCES unidad_medida(id_unidad),
    descripcion TEXT,
    CHECK (cantidad_base IS NULL OR cantidad_base >= 0)
);

CREATE TABLE IF NOT EXISTS principio_activo (
    id_principio_activo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE IF NOT EXISTS medicamento_principio_activo (
    id_medicamento BIGINT NOT NULL REFERENCES medicamento(id_medicamento),
    id_principio_activo BIGINT NOT NULL REFERENCES principio_activo(id_principio_activo),
    cantidad NUMERIC(12,4),
    id_unidad_cantidad BIGINT REFERENCES unidad_medida(id_unidad),
    PRIMARY KEY (id_medicamento, id_principio_activo),
    CHECK (cantidad IS NULL OR cantidad >= 0)
);

CREATE TABLE IF NOT EXISTS receta (
    id_receta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta BIGINT NOT NULL REFERENCES consulta(id_consulta),
    id_personal_prescriptor BIGINT NOT NULL REFERENCES personal_medico(id_personal),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    indicaciones_generales TEXT
);

CREATE TABLE IF NOT EXISTS detalle_receta (
    id_detalle_receta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_receta BIGINT NOT NULL REFERENCES receta(id_receta),
    id_medicamento BIGINT NOT NULL REFERENCES medicamento(id_medicamento),
    dosis_cantidad NUMERIC(12,4),
    id_unidad_dosis BIGINT REFERENCES unidad_medida(id_unidad),
    frecuencia VARCHAR(120),
    duracion_dias INTEGER,
    via_administracion VARCHAR(100),
    instrucciones TEXT,
    CHECK (dosis_cantidad IS NULL OR dosis_cantidad >= 0),
    CHECK (duracion_dias IS NULL OR duracion_dias >= 0)
);

CREATE TABLE IF NOT EXISTS examen_medico (
    id_examen BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL UNIQUE,
    descripcion TEXT,
    tipo VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS orden_examen (
    id_orden BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta BIGINT NOT NULL REFERENCES consulta(id_consulta),
    id_personal_solicitante BIGINT NOT NULL REFERENCES personal_medico(id_personal),
    fecha_solicitud TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    indicaciones TEXT,
    estado VARCHAR(30) NOT NULL DEFAULT 'SOLICITADA'
);

CREATE TABLE IF NOT EXISTS detalle_orden_examen (
    id_detalle_orden BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden BIGINT NOT NULL REFERENCES orden_examen(id_orden),
    id_examen BIGINT NOT NULL REFERENCES examen_medico(id_examen),
    indicaciones_muestra TEXT
);

CREATE TABLE IF NOT EXISTS resultado_examen (
    id_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_detalle_orden BIGINT NOT NULL REFERENCES detalle_orden_examen(id_detalle_orden),
    version INTEGER NOT NULL DEFAULT 1,
    fecha_resultado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    informe_texto TEXT,
    observaciones TEXT,
    archivo_resultado TEXT,
    UNIQUE (id_detalle_orden, version),
    CHECK (version > 0)
);

CREATE TABLE IF NOT EXISTS parametro_examen (
    id_parametro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE IF NOT EXISTS resultado_detalle (
    id_resultado_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_resultado BIGINT NOT NULL REFERENCES resultado_examen(id_resultado),
    secuencia INTEGER NOT NULL,
    id_parametro BIGINT NOT NULL REFERENCES parametro_examen(id_parametro),
    fecha_hora_medicion TIMESTAMP,
    valor_numerico NUMERIC(18,6),
    valor_texto TEXT,
    id_unidad BIGINT REFERENCES unidad_medida(id_unidad),
    referencia_inferior NUMERIC(18,6),
    referencia_superior NUMERIC(18,6),
    referencia_texto TEXT,
    observaciones TEXT,
    UNIQUE (id_resultado, secuencia),
    CHECK (secuencia > 0)
);

CREATE TABLE IF NOT EXISTS hospitalizacion (
    id_hospitalizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
    id_personal_responsable_ingreso BIGINT NOT NULL REFERENCES personal_medico(id_personal),
    fecha_ingreso TIMESTAMP NOT NULL,
    fecha_egreso TIMESTAMP,
    motivo_ingreso TEXT NOT NULL,
    observaciones TEXT,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVA',
    CHECK (fecha_egreso IS NULL OR fecha_egreso >= fecha_ingreso)
);

CREATE TABLE IF NOT EXISTS hospitalizacion_consulta (
    id_consulta BIGINT PRIMARY KEY REFERENCES consulta(id_consulta),
    id_hospitalizacion BIGINT NOT NULL REFERENCES hospitalizacion(id_hospitalizacion)
);

CREATE TABLE IF NOT EXISTS hospitalizacion_diagnostico (
    id_hospitalizacion_diagnostico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hospitalizacion BIGINT NOT NULL REFERENCES hospitalizacion(id_hospitalizacion),
    id_diagnostico BIGINT NOT NULL REFERENCES diagnostico(id_diagnostico),
    tipo_en_hospitalizacion VARCHAR(60),
    fecha_vinculacion DATE NOT NULL DEFAULT CURRENT_DATE,
    observaciones TEXT,
    UNIQUE (id_hospitalizacion, id_diagnostico)
);

CREATE TABLE IF NOT EXISTS habitacion (
    id_habitacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(30) NOT NULL,
    piso VARCHAR(30),
    tipo VARCHAR(80),
    estado_operativo VARCHAR(30) NOT NULL DEFAULT 'DISPONIBLE',
    UNIQUE (piso, numero)
);

CREATE TABLE IF NOT EXISTS cama (
    id_cama BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_habitacion BIGINT NOT NULL REFERENCES habitacion(id_habitacion),
    numero_cama VARCHAR(30) NOT NULL,
    estado_operativo VARCHAR(30) NOT NULL DEFAULT 'DISPONIBLE',
    UNIQUE (id_habitacion, numero_cama)
);

CREATE TABLE IF NOT EXISTS asignacion_cama (
    id_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hospitalizacion BIGINT NOT NULL REFERENCES hospitalizacion(id_hospitalizacion),
    id_cama BIGINT NOT NULL REFERENCES cama(id_cama),
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP,
    CHECK (fecha_hora_fin IS NULL OR fecha_hora_fin >= fecha_hora_inicio)
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal BIGINT NOT NULL UNIQUE REFERENCES personal_medico(id_personal),
    nombre_usuario VARCHAR(80) NOT NULL UNIQUE,
    contrasena_hash TEXT NOT NULL,
    ultimo_acceso TIMESTAMP,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE IF NOT EXISTS rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE IF NOT EXISTS usuario_rol (
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    id_rol BIGINT NOT NULL REFERENCES rol(id_rol),
    PRIMARY KEY (id_usuario, id_rol)
);

CREATE TABLE IF NOT EXISTS auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES usuario(id_usuario),
    accion VARCHAR(100) NOT NULL,
    tabla_afectada VARCHAR(100) NOT NULL,
    registro_afectado VARCHAR(120),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    detalle TEXT
);

CREATE TABLE IF NOT EXISTS aseguradora (
    id_aseguradora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL UNIQUE,
    nit VARCHAR(30) UNIQUE,
    telefono VARCHAR(30),
    correo VARCHAR(254),
    direccion TEXT,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVA'
);

CREATE TABLE IF NOT EXISTS plan_seguro (
    id_plan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aseguradora BIGINT NOT NULL REFERENCES aseguradora(id_aseguradora),
    nombre_plan VARCHAR(150) NOT NULL,
    version_plan VARCHAR(40),
    descripcion TEXT,
    porcentaje_cobertura NUMERIC(5,2),
    monto_maximo_cobertura NUMERIC(14,2),
    moneda CHAR(3),
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVO',
    CHECK (porcentaje_cobertura IS NULL OR porcentaje_cobertura BETWEEN 0 AND 100),
    CHECK (monto_maximo_cobertura IS NULL OR monto_maximo_cobertura >= 0),
    UNIQUE (id_aseguradora, nombre_plan, version_plan)
);

CREATE TABLE IF NOT EXISTS titular_seguro (
    id_titular BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    primer_nombre VARCHAR(80) NOT NULL,
    segundo_nombre VARCHAR(80),
    primer_apellido VARCHAR(80) NOT NULL,
    segundo_apellido VARCHAR(80),
    cui VARCHAR(20) UNIQUE,
    telefono VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS poliza (
    id_poliza BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_plan BIGINT NOT NULL REFERENCES plan_seguro(id_plan),
    id_titular BIGINT NOT NULL REFERENCES titular_seguro(id_titular),
    numero_poliza VARCHAR(80) NOT NULL UNIQUE,
    fecha_inicio DATE NOT NULL,
    fecha_vencimiento DATE,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVA',
    CHECK (fecha_vencimiento IS NULL OR fecha_vencimiento >= fecha_inicio)
);

CREATE TABLE IF NOT EXISTS paciente_poliza (
    id_paciente_poliza BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
    id_poliza BIGINT NOT NULL REFERENCES poliza(id_poliza),
    numero_afiliado VARCHAR(80),
    parentesco_titular VARCHAR(60),
    fecha_inicio_cobertura DATE,
    fecha_fin_cobertura DATE,
    estado_afiliacion VARCHAR(30) NOT NULL DEFAULT 'ACTIVA',
    UNIQUE (id_paciente, id_poliza),
    CHECK (fecha_fin_cobertura IS NULL OR fecha_inicio_cobertura IS NULL OR fecha_fin_cobertura >= fecha_inicio_cobertura)
);

-- Índices para las relaciones y consultas habituales del expediente.
CREATE INDEX IF NOT EXISTS ix_cita_paciente_fecha ON cita (id_paciente, fecha_hora_inicio);
CREATE INDEX IF NOT EXISTS ix_consulta_historial_fecha ON consulta (id_historial, fecha_hora);
CREATE INDEX IF NOT EXISTS ix_diagnostico_consulta ON diagnostico (id_consulta);
CREATE INDEX IF NOT EXISTS ix_resultado_detalle_orden ON resultado_examen (id_detalle_orden, fecha_resultado);
CREATE INDEX IF NOT EXISTS ix_hospitalizacion_paciente_fecha ON hospitalizacion (id_paciente, fecha_ingreso);
CREATE INDEX IF NOT EXISTS ix_auditoria_fecha ON auditoria (fecha_hora);

COMMIT;
